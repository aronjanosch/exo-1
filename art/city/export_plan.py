"""Writes the city plan as data for the game: content/city/plan.json (round 6).

Plain Python, no Blender: city_plan.py is data already. Coordinates are shifted so the plan's
centre is the origin of the place `city` (content/place/city.json). Each model also gets its
bounding box from the glb (accessor min/max of POSITION, glTF axes: x, y up, z = -north), so the
game can give buildings a box collider without loading meshes.

Run from the repo root: python3 -I art/city/export_plan.py
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
import city_plan as plan  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
CITY = os.path.join(ROOT, "content", "city")


def glb_bounds(path):
    with open(path, "rb") as f:
        data = f.read()
    length = struct.unpack_from("<I", data, 12)[0]
    gltf = json.loads(data[20:20 + length])
    lo, hi = [1e9] * 3, [-1e9] * 3
    for mesh in gltf.get("meshes", []):
        for prim in mesh["primitives"]:
            acc = gltf["accessors"][prim["attributes"]["POSITION"]]
            for i in range(3):
                lo[i] = min(lo[i], acc["min"][i])
                hi[i] = max(hi[i], acc["max"][i])
    # Node transforms are ignored: the kit exports one node at the origin per model.
    return [round(v, 3) for v in lo], [round(v, 3) for v in hi]


def main():
    xs = [p[1] for p in plan.PLACEMENTS]
    ys = [p[2] for p in plan.PLACEMENTS]
    cx, cy = round((min(xs) + max(xs)) / 2), round((min(ys) + max(ys)) / 2)
    items = []
    for p in plan.PLACEMENTS:
        item = {"model": p[0], "at": [round(p[1] - cx, 3), round(p[2] - cy, 3), round(p[3], 3)], "turn_deg": p[4]}
        if len(p) > 5 and p[5].get("fit"):
            item["fit"] = p[5]["fit"]
        items.append(item)
    models = {}
    for mid in sorted({p[0] for p in plan.PLACEMENTS}):
        lo, hi = glb_bounds(os.path.join(CITY, mid + ".glb"))
        models[mid] = {"min": lo, "max": hi}
    quests = [{"id": q, "at": [round(x - cx, 3), round(y - cy, 3)]} for q, x, y in plan.QUESTS]
    out = {
        "_comment": "Generated by art/city/export_plan.py from art/city/city_plan.py; do not edit by hand.",
        "centre_in_plan": [cx, cy],
        "placements": items,
        "models": models,
        "quests": quests,
    }
    with open(os.path.join(CITY, "plan.json"), "w") as f:
        json.dump(out, f, indent=1)
        f.write("\n")
    print(f"{len(items)} placements, {len(models)} models, centre {cx},{cy}")


if __name__ == "__main__":
    main()
