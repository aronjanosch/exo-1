def check(source_before):
    problems=[]
    unchanged=fingerprint(source)==source_before
    if not unchanged:problems.append('source ship changed')
    # Floor plates must not bridge the existing access opening.
    for o in kit.objects:
        if 'Deck plate' in o.name:
            x,y,z=o.location;dx,dy,dz=(v/2 for v in o.dimensions)
            if x+dx>HOLE[0]+.001 and x-dx<HOLE[1]-.001 and y+dy>HOLE[2]+.001 and y-dy<HOLE[3]-.001:problems.append('floor plate over ladder opening')
    # Keep an unobstructed first metre behind each existing door opening.
    for name,edge,t,w in DOORS:
        if edge=='N':box=(t-w/2,t+w/2,Y1-1,Y1-.15)
        elif edge=='S':box=(t-w/2,t+w/2,Y0+.15,Y0+1)
        elif edge=='W':box=(X0+.15,X0+1,t-w/2,t+w/2)
        else:box=(X1-1,X1-.15,t-w/2,t+w/2)
        for o in kit.objects:
            pts=[o.matrix_world@Vector(v) for v in o.bound_box]
            lo=[min(p[i] for p in pts) for i in range(3)];hi=[max(p[i] for p in pts) for i in range(3)]
            if hi[2]<=.04 or lo[2]>=2.2:continue
            if lo[0]<box[1]-.005 and hi[0]>box[0]+.005 and lo[1]<box[3]-.005 and hi[1]>box[2]+.005:
                problems.append('door approach '+name+': '+o.name)
    geometry=[]
    for o in kit.objects:
        vertices=[tuple(round(v,6) for v in o.matrix_world@p.co) for p in o.data.vertices]
        geometry.append((vertices,[tuple(p.vertices) for p in o.data.polygons],list(o.data.materials[0].diffuse_color)))
    geometry_hash=hashlib.sha256(repr(sorted(geometry,key=repr)).encode()).hexdigest()
    report={'problems':problems,'source_unchanged':unchanged,'room_m':[8.4,7.2],
            'main_floor_z':0,'service_bay_z':.16,'ladder_destination_z':-2.9,
            'door_widths_m':{name+' '+edge:w for name,edge,t,w in DOORS},
            'new_objects':len(kit.objects),'unique_meshes':len({o.data for o in kit.objects if o.type=='MESH'}),
            'turret_stations':4,'initial_turrets':2,
            'source_fingerprint':source_before,'interior_fingerprint':geometry_hash,
            'scope':'architecture study; no game collision or ladder gameplay validation'}
    (OUT/'geometry-check.json').write_text(json.dumps(report,indent=2)+'\n')
    for p in problems:print('PROBLEM: '+p)
    print(json.dumps(report));return report


def main():
    global kit,review,study,source,box_meshes,floor,lining,teal,steel,ochre,amber,placeholder,cream
    parser=argparse.ArgumentParser();parser.add_argument('--render',action='store_true');parser.add_argument('--export',action='store_true');parser.add_argument('--replace',action='store_true')
    args=parser.parse_args(sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else [])
    OUT.mkdir(parents=True,exist_ok=True)
    existing=[s for s in bpy.data.scenes if s.name.startswith(PREFIX)]
    if existing and not args.replace:raise RuntimeError('Study already exists; inspect before --replace.')
    if existing:
        for s in existing:bpy.data.scenes.remove(s)
        for c in list(bpy.data.collections):
            if c.name.startswith(PREFIX):
                for o in list(c.objects):
                    if o.name.startswith(PREFIX):bpy.data.objects.remove(o,do_unlink=True)
                bpy.data.collections.remove(c)
    source=bpy.data.scenes.get(SOURCE)
    reference=OUT/'live-shell-reference.blend'
    if source is None:
        with bpy.data.libraries.load(str(reference),link=False) as (a,b):b.scenes=[SOURCE]
        source=bpy.data.scenes[SOURCE]
    before=fingerprint(source)
    # Check against the live opening: never silently build against the older plan.
    floors=[o for o in source.objects if o.name.startswith('Turret deck around ladder')]
    pts=[o.matrix_world@Vector(v) for o in floors for v in o.bound_box]
    assert abs(min(p.x for p in pts)-X0)<.001 and abs(max(p.y for p in pts)-Y1)<.001,'Unexpected live room dimensions'
    if not reference.exists():bpy.data.libraries.write(str(reference),{source},fake_user=True,compress=True)
    study=bpy.data.scenes.new(PREFIX+' | Architecture');study.unit_settings.system='METRIC'
    for c in source.collection.children:
        if not any(t in c.name for t in ['Labels','Guides','Sightline','Ground','Plan','Gear stowed']):study.collection.children.link(c)
    kit=bpy.data.collections.new(PREFIX+' modular interior');study.collection.children.link(kit)
    review=bpy.data.collections.new(PREFIX+' lighting');study.collection.children.link(review)
    bpy.context.window.scene=study;box_meshes={}
    floor=material('charcoal deck',(.105,.13,.125),.2)
    lining=material('warm lining',(.43,.40,.31))
    teal=material('painted petrol',(.075,.19,.175),.18)
    steel=material('dark iron',(.045,.065,.064),.35)
    ochre=material('ochre edges',(.65,.33,.065),.1)
    amber=material('warm diffusers',(1,.62,.25),emission=4)
    placeholder=material('plain grey placeholders',(.28,.29,.28))
    cream=material('plan light ink',(.83,.82,.71))
    study.world=bpy.data.worlds.new(PREFIX+' space');study.world.use_nodes=True
    study.world.node_tree.nodes['Background'].inputs[0].default_value=(.035,.055,.09,1)
    study.world.node_tree.nodes['Background'].inputs[1].default_value=.25
    study.render.engine='BLENDER_EEVEE';study.render.resolution_x=1600;study.render.resolution_y=1000;study.render.resolution_percentage=100
    study.view_settings.view_transform='AgX';study.view_settings.look='AgX - Medium High Contrast'
    build_kit()
    first=camera('01 Main door eye 1.70m',(-8.00,.02,1.70),(-1.70,.48,1.90),lens=20)
    opposite=camera('02 Opposite corner eye 2.15m',(-.63,2.93,2.15),(-5.25,-.55,1.80),lens=20)
    study.camera=first;plan=make_plan();bpy.context.window.scene=study
    study['description']='Live-sized architecture proposal. Source ship untouched. One +0.16 m service step, existing -2.90 m ladder.'
    bpy.context.view_layer.update()
    report=check(before)
    if report['problems']:raise RuntimeError('Geometry checks failed')
    if args.export:
        bpy.ops.object.select_all(action='DESELECT')
        for o in kit.objects:o.select_set(True)
        bpy.ops.export_scene.gltf(filepath=str(OUT/'turret-hub-study.glb'),use_selection=True,export_format='GLB',export_apply=True)
        bpy.ops.object.select_all(action='DESELECT')
    if args.render:
        for s,c,name in [(study,first,'01-door'),(study,opposite,'02-opposite'),(plan,plan.camera,'03-plan')]:
            bpy.context.window.scene=s;s.camera=c;s.render.filepath=str(OUT/(name+'.png'));bpy.ops.render.render(write_still=True)
